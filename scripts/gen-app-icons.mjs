#!/usr/bin/env node
/**
 * Pull one square mark per project out of Verde and freeze them into this project.
 *
 * Built renders as a store rather than a ledger, and a store needs every app to
 * have an icon. Three projects have a real screenshot; the rest would otherwise
 * be blank squares. v1 solved this in build.mjs by generating the missing ones
 * from Verde's seeded imagery, and this is that idea carried across — a figure
 * seeded by project id, so a given project keeps the same mark forever instead
 * of shuffling when the list is reordered.
 *
 *   node scripts/gen-app-icons.mjs        regenerate src/generated/app-icons.ts
 *   VERDE=/path/to/verde-design-system node scripts/gen-app-icons.mjs
 *
 * Same contract as gen-ridge.mjs: run the generator once and commit the result,
 * so the app carries SVG rather than a 1000-line generator and building never
 * requires the Verde checkout to be present.
 *
 * One thing here differs from v1 and is load-bearing. v1 passed
 * `var(--verde-color-surface)` and `var(--verde-color-on-surface)` for the
 * ground and the trunk. This project defines neither — it has `--verde-viz-*`
 * and shadcn's `--background` / `--foreground`, nothing else. Those names would
 * resolve to nothing here and the figures would paint with invalid fills, so the
 * palette below uses this project's own roles, exactly as gen-ridge.mjs does.
 */

import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(here, '..');
const VERDE = process.env.VERDE ?? path.join(os.homedir(), 'Downloads', 'verde-design-system');

if (!fs.existsSync(path.join(VERDE, 'src/design-system/imagery.mjs'))) {
  console.error(`Verde not found at ${VERDE}. Set VERDE=/path/to/verde-design-system.`);
  console.error('The committed src/generated/app-icons.ts still builds without it.');
  process.exit(1);
}

const { figure, caption, FIGURE_FORMS } = await import(
  path.join(VERDE, 'src/design-system/imagery.mjs')
);

const projects = JSON.parse(
  fs.readFileSync(path.join(root, 'src/content/projects.json'), 'utf8'),
);

/** This project's own page ground, so the figures follow light and dark here. */
const SKY = 'hsl(var(--background))';

/* A geometric figure is data-adjacent by Verde's own account of that family, so
   it takes the full data-visualization ramp. tokens.json defines ordered ramps
   only for the landscape forms, which is why there is nothing to read here. */
const CANOPY = ['forest', 'brass', 'slate', 'sage', 'clay', 'moss']
  .map((n) => `var(--verde-viz-${n})`);

/** v1's hash, kept byte for byte so a project keeps the mark it already had. */
const formFor = (id) =>
  FIGURE_FORMS[
    Math.abs([...id].reduce((h, c) => (h * 31 + c.charCodeAt(0)) | 0, 7)) % FIGURE_FORMS.length
  ];

const mark = (id) =>
  figure(`verdevista-app-${id}`, {
    form: formFor(id),
    ratio: '1:1',
    fills: CANOPY,
    ground: SKY,
    palette: {
      sky: SKY,
      ground: 'var(--verde-viz-forest)',
      trunk: 'currentColor',
      accent: 'var(--verde-viz-brass)',
      canopy: CANOPY,
    },
  });

/* A project's own screenshot wins. The icon paths in projects.json are v1's
   (`assets/...`); this project keeps the same files under public/media, so match
   on the basename and confirm the file is actually there rather than trusting
   the field — a missing file should fall back to a figure, not to a broken img. */
const photos = {};
const figures = {};
const skipped = [];

for (const p of projects) {
  if (p.placeholder) { skipped.push(p.id); continue; }
  const file = p.icon?.file ? `media/${path.basename(p.icon.file)}` : null;
  if (file && fs.existsSync(path.join(root, 'public', file))) {
    photos[p.id] = { src: file, alt: p.icon.alt ?? '' };
  } else {
    if (file) console.warn(`  ! icon missing on disk, falling back to a figure: ${file} (${p.id})`);
    figures[p.id] = mark(p.id);
  }
}

for (const [id, svg] of Object.entries(figures)) {
  if (/#[0-9a-fA-F]{3,8}\b/.test(svg)) {
    console.error(`${id}: figure contains a hex color, so it cannot follow the theme`);
    process.exit(1);
  }
  if (!/viewBox="/.test(svg)) {
    console.error(`${id}: figure has no viewBox, so it would render zero-height`);
    process.exit(1);
  }
}

const out = `/* Generated by scripts/gen-app-icons.mjs — do not edit by hand.
 *
 * One square mark per project, for the Built section's store grid.
 *
 * APP_PHOTOS are the three projects with a real screenshot. APP_FIGURES are the
 * rest, drawn by Verde's seeded generator so every app has an icon rather than
 * a blank square — see the generator for the seeding and the palette.
 *
 * Fills are CSS roles, resolved at paint time, so these follow the theme toggle.
 * The placeholder project is excluded here rather than filtered in the view:
${skipped.map((id) => ` *   skipped ${id}`).join('\n') || ' *   (none skipped)'}
 */

export const APP_PHOTOS: Record<string, { src: string; alt: string }> = ${JSON.stringify(photos, null, 2)};

export const APP_FIGURES: Record<string, string> = {
${Object.entries(figures).map(([id, svg]) => `  ${JSON.stringify(id)}: ${JSON.stringify(svg)},`).join('\n')}
};
`;

const dest = path.join(root, 'src/generated/app-icons.ts');
fs.writeFileSync(dest, out);
console.log(`  photos  ${Object.keys(photos).join(', ')}`);
for (const id of Object.keys(figures)) console.log(`  figure  ${caption(`verdevista-app-${id}`, formFor(id))}  (${id})`);
if (skipped.length) console.log(`  skipped ${skipped.join(', ')} (placeholder)`);
console.log(`  ${(out.length / 1024).toFixed(1)}KB -> ${path.relative(process.cwd(), dest)}`);
